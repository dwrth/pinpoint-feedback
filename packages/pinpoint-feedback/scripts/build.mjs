import { readFileSync } from "node:fs";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(pkgDir, "../..");
const distDir = join(pkgDir, "dist");
const require = createRequire(join(pkgDir, "package.json"));

/**
 * Each entry re-exports one internal package. Entries marked `client` are React client
 * boundaries: Next.js requires the "use client" directive in the module that a Server
 * Component imports, and rejects `export *` inside client boundaries, so their value
 * exports are listed by name (collected from the built package).
 */
const entries = [
  { file: "index", from: "@pinpoint-feedback/core" },
  { file: "core", from: "@pinpoint-feedback/core" },
  { file: "server", from: "@pinpoint-feedback/server" },
  { file: "react", from: "@pinpoint-feedback/react", client: true },
  { file: "nextjs", from: "@pinpoint-feedback/nextjs", client: true },
  { file: "nextjs-server", from: "@pinpoint-feedback/nextjs/server" },
];

const BANNER = "// Generated by scripts/build.mjs. Do not edit.\n";

function resolveDistFile(specifier) {
  const [scope, name, ...rest] = specifier.split("/");
  const pkgJsonPath = require.resolve(`${scope}/${name}/package.json`);
  const pkg = JSON.parse(readFileSync(pkgJsonPath, "utf8"));
  const subpath = rest.length ? `./${rest.join("/")}` : ".";
  const target = pkg.exports?.[subpath];
  const file = typeof target === "string" ? target : (target?.import ?? target?.default);
  if (!file) throw new Error(`${specifier}: no "import" export for ${subpath}`);
  return join(dirname(pkgJsonPath), file);
}

function stripComments(code) {
  return code.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:"'`\\])\/\/[^\n]*/g, "$1");
}

/** Collects the runtime export names of a built ES module (Vite/Rolldown output). */
async function collectExportNames(file, seen = new Set()) {
  if (seen.has(file)) return new Set();
  seen.add(file);
  const code = stripComments(await readFile(file, "utf8"));
  const names = new Set();

  for (const m of code.matchAll(/\bexport\s*\{([^}]*)\}\s*(?:from\s*["']([^"']+)["'])?/g)) {
    for (const part of m[1].split(",")) {
      const spec = part.trim().replace(/^type\s+/, "");
      if (!spec) continue;
      const alias = spec.split(/\s+as\s+/).pop().trim().replace(/^["']|["']$/g, "");
      if (alias !== "default") names.add(alias);
    }
  }
  for (const m of code.matchAll(/\bexport\s+(?:async\s+)?(?:function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/g)) {
    names.add(m[1]);
  }
  for (const m of code.matchAll(/\bexport\s*\*\s*from\s*["']([^"']+)["']/g)) {
    const target = m[1].startsWith(".") ? resolve(dirname(file), m[1]) : resolveDistFile(m[1]);
    for (const name of await collectExportNames(target, seen)) names.add(name);
  }
  return names;
}

async function build() {
  await rm(distDir, { recursive: true, force: true });
  await mkdir(distDir, { recursive: true });

  for (const entry of entries) {
    let js;
    if (entry.client) {
      const names = [...(await collectExportNames(resolveDistFile(entry.from)))].sort();
      if (names.length === 0) throw new Error(`${entry.from}: found no exports; build it first`);
      js = `"use client";\n${BANNER}export {\n${names.map((n) => `  ${n},`).join("\n")}\n} from "${entry.from}";\n`;
    } else {
      js = `${BANNER}export * from "${entry.from}";\n`;
    }
    await writeFile(join(distDir, `${entry.file}.js`), js);
    await writeFile(join(distDir, `${entry.file}.d.ts`), `${BANNER}export * from "${entry.from}";\n`);
  }

  await copyFile(join(repoRoot, "README.md"), join(pkgDir, "README.md"));
  await copyFile(join(repoRoot, "LICENSE"), join(pkgDir, "LICENSE"));
  console.log(`pinpoint-feedback: wrote ${entries.length} entries to dist/`);
}

build().catch((error) => {
  console.error(error);
  process.exit(1);
});
